import hashlib
import math


def make_keys(p: int, q: int, e: int):
    n = p * q
    phi = (p - 1) * (q - 1)
    if math.gcd(e, phi) != 1:
        raise ValueError(f"НСД(e, φ) = {math.gcd(e, phi)} ≠ 1, оберіть інше e")
    d = pow(e, -1, phi)
    return n, phi, d


def h_mod(message: str, n: int) -> int:
    return int(hashlib.sha256(message.encode("utf-8")).hexdigest(), 16) % n


def main() -> None:
    # Крок 1: ключі.
    p, q = 101, 113
    e = 17
    n, phi, d = make_keys(p, q, e)
    print(f"p = {p}, q = {q}")
    print(f"n = p·q = {n}")
    print(f"φ = (p−1)(q−1) = {phi}")
    print(f"e = {e}, НСД(e, φ) = {math.gcd(e, phi)}")
    print(f"d = {d}  (перевірка e·d mod φ = {(e * d) % phi})")
    print(f"Публічний ключ (e, n) = ({e}, {n})")
    print(f"Приватний ключ (d, n) = ({d}, {n})")
    print()

    # Крок 2: шифрування і розшифрування
    m = 65                 # має бути меншим за n
    c = pow(m, e, n)
    m2 = pow(c, d, n)
    print(f"Шифрування: c = {m}^{e} mod {n} = {c}")
    print(f"Розшифрування: m = {c}^{d} mod {n} = {m2}")
    print("Збіглося:", m == m2)
    print()

    # Крок 3: цифровий підпис
    msg = "Акт приймання №1"
    h = h_mod(msg, n)
    s = pow(h, d, n)
    print(f"Повідомлення: {msg!r}")
    print(f"h = SHA-256 mod n = {h}")
    print(f"Підпис s = h^d mod n = {s}")
    print(f"Перевірка: s^e mod n = {pow(s, e, n)}  → підпис правильний: {pow(s, e, n) == h}")
    print()

    msg_changed = "Акт приймання №2"   # змінено один символ
    h2 = h_mod(msg_changed, n)
    print(f"Змінене повідомлення: {msg_changed!r}")
    print(f"h зміненого = {h2}")
    print(f"Перевірка старим підписом: s^e mod n = {pow(s, e, n)} → підпис правильний: {pow(s, e, n) == h2}")


if __name__ == "__main__":
    main()

